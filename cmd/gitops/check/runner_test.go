func Test_Check_Adopt(t *testing.T) {
	fs := generatedRepo(t)
	out := new(bytes.Buffer)

	err := newTestRunner(fs, true, out).run(context.Background(), newTestCommand(testRepo, false), nil)
	if err != nil {
		t.Fatalf("unexpected error: %s", err)
	}

	md, err := metadata.Load(&afero.Afero{Fs: fs}, testRepo)
	if err != nil {
		t.Fatalf("expected adoption to write the metadata file: %s", err)
	}

	expected := map[string]string{
		metadata.LayerManagementCluster: testMC,
		metadata.LayerOrganization:      testOrg,
		metadata.LayerWorkloadCluster:   testWC,
	}
	if len(md.Layers) != len(expected) {
		t.Fatalf("expected %d layers, got %d", len(expected), len(md.Layers))
	}
	for _, l := range md.Layers {
		if expected[l.Kind] != l.Path {
			t.Errorf("unexpected layer recorded: %s at %s", l.Kind, l.Path)
		}
	}

	// Adoption must be honest about what it cannot know.
	if !strings.Contains(out.String(), "not detectable") {
		t.Errorf("expected adoption to warn that earlier drift is invisible, got:\n%s", out.String())
	}

	// The repository is tracked now, so a plain check has to pass.
	err = newTestRunner(fs, false, new(bytes.Buffer)).run(context.Background(), newTestCommand(testRepo, false), nil)
	if err != nil {
		t.Errorf("expected the adopted repository to check out clean, got: %s", err)
	}
}

func Test_Check_AdoptDryRunWritesNothing(t *testing.T) {
	fs := generatedRepo(t)
	out := new(bytes.Buffer)

	err := newTestRunner(fs, true, out).run(context.Background(), newTestCommand(testRepo, true), nil)
	if err != nil {
		t.Fatalf("unexpected error: %s", err)
	}

	exists, err := afero.Exists(fs, metadata.FilePath(testRepo))
	if err != nil {
		t.Fatalf("unexpected error: %s", err)
	}
	if exists {
		t.Error("a dry run must not write the metadata file")
	}
	if !strings.Contains(out.String(), metadata.Kind) {
		t.Errorf("expected the dry run to print what it would write, got:\n%s", out.String())
	}
}

func Test_Check_AdoptIsIdempotent(t *testing.T) {
	fs := generatedRepo(t)

	err := newTestRunner(fs, true, new(bytes.Buffer)).run(context.Background(), newTestCommand(testRepo, false), nil)
	if err != nil {
		t.Fatalf("unexpected error: %s", err)
	}

	out := new(bytes.Buffer)
	err = newTestRunner(fs, true, out).run(context.Background(), newTestCommand(testRepo, false), nil)
	if err != nil {
		t.Fatalf("unexpected error: %s", err)
	}

	if !strings.Contains(out.String(), "Nothing to adopt") {
		t.Errorf("expected a second adoption to be a no-op, got:\n%s", out.String())
	}
}

// Adopting into a repository that is already tracked must fill the gaps
// without bumping what is already recorded, or drift would be erased.
func Test_Check_AdoptDoesNotEraseDrift(t *testing.T) {
	fs := generatedRepo(t)

	md := metadata.New()
	md.Upsert(metadata.Layer{Kind: metadata.LayerManagementCluster, Path: testMC})
	md.Layers[0].StructureVersion = metadata.StructureVersion - 1
	err := metadata.Save(&afero.Afero{Fs: fs}, testRepo, md)
	if err != nil {
		t.Fatalf("unexpected error: %s", err)
	}

	err = newTestRunner(fs, true, new(bytes.Buffer)).run(context.Background(), newTestCommand(testRepo, false), nil)
	if err != nil {
		t.Fatalf("unexpected error: %s", err)
	}

	reloaded, err := metadata.Load(&afero.Afero{Fs: fs}, testRepo)
	if err != nil {
		t.Fatalf("unexpected error: %s", err)
	}

	for _, l := range reloaded.Layers {
		if l.Path == testMC && l.StructureVersion != metadata.StructureVersion-1 {
			t.Errorf("adoption must not bump an already recorded layer, got version %d", l.StructureVersion)
		}
	}

	if len(reloaded.Layers) < 3 {
		t.Errorf("expected adoption to add the untracked layers, got %d", len(reloaded.Layers))
	}
}
