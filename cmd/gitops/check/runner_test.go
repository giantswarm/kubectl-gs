const (
	testRepo = "/repo"
	testMC   = "management-clusters/demomc"
	testOrg  = testMC + "/organizations/demoorg"
	testWC   = testOrg + "/workload-clusters/demowc"
)

// newTestCommand mimics the cobra tree the runner reads its inherited flags
// from: `gitops` owns --local-path and --dry-run, `check` is its child.
func newTestCommand(repoPath string, dryRun bool) *cobra.Command {
	parent := &cobra.Command{Use: "gitops"}
	parent.PersistentFlags().String("local-path", ".", "")
	parent.PersistentFlags().Bool("dry-run", false, "")
	_ = parent.PersistentFlags().Set("local-path", repoPath)
	if dryRun {
		_ = parent.PersistentFlags().Set("dry-run", "true")
	}

	child := &cobra.Command{Use: "check"}
	parent.AddCommand(child)

	return child
}

func newTestRunner(fs afero.Fs, adopt bool, out *bytes.Buffer) *runner {
	return &runner{
		flag:   &flag{Adopt: adopt},
		fs:     &afero.Afero{Fs: fs},
		stdout: out,
		stderr: out,
	}
}

// generatedRepo lays out a repository as `kubectl gs gitops` would have.
func generatedRepo(t *testing.T) afero.Fs {
	t.Helper()

	fs := &afero.Afero{Fs: afero.NewMemMapFs()}

	dirs := []string{
		testWC + "/mapi/apps",
	}
	for _, d := range dirs {
		err := fs.MkdirAll(testRepo+"/"+d, 0755)
		if err != nil {
			t.Fatalf("unexpected error: %s", err)
		}
	}

	return fs
}

func Test_Check_ReportsUpToDate(t *testing.T) {
	fs := generatedRepo(t)
	out := new(bytes.Buffer)

	md := metadata.New()
	md.Upsert(metadata.Layer{Kind: metadata.LayerManagementCluster, Path: testMC})
	err := metadata.Save(&afero.Afero{Fs: fs}, testRepo, md)
	if err != nil {
		t.Fatalf("unexpected error: %s", err)
	}

	err = newTestRunner(fs, false, out).run(context.Background(), newTestCommand(testRepo, false), nil)
	if err != nil {
		t.Fatalf("expected an up to date repository to pass, got: %s", err)
	}

	if !strings.Contains(out.String(), "up to date") {
		t.Errorf("expected the report to say the repository is up to date, got:\n%s", out.String())
	}
}

func Test_Check_FailsOnDrift(t *testing.T) {
	fs := generatedRepo(t)
	out := new(bytes.Buffer)

	md := metadata.New()
	md.Upsert(metadata.Layer{Kind: metadata.LayerManagementCluster, Path: testMC})
	// Pretend the layer was generated by an older kubectl-gs.
	md.Layers[0].StructureVersion = metadata.StructureVersion - 1
	err := metadata.Save(&afero.Afero{Fs: fs}, testRepo, md)
	if err != nil {
		t.Fatalf("unexpected error: %s", err)
	}

	err = newTestRunner(fs, false, out).run(context.Background(), newTestCommand(testRepo, false), nil)
	if err == nil {
		t.Fatal("expected an outdated repository to fail, so the command is usable as a CI check")
	}

	if !strings.Contains(out.String(), "outdated") {
		t.Errorf("expected the report to flag the outdated layer, got:\n%s", out.String())
	}
	if !strings.Contains(out.String(), "1 layer(s) out of sync") {
		t.Errorf("expected a summary of what is out of sync, got:\n%s", out.String())
	}
}

func Test_Check_FailsOnRepositoryLevelDrift(t *testing.T) {
	fs := generatedRepo(t)
	out := new(bytes.Buffer)

	// A repository that only ever had `gitops init` run against it records no
	// layers, but can still fall behind.
	md := metadata.New()
	md.StructureVersion = metadata.StructureVersion - 1
	err := metadata.Save(&afero.Afero{Fs: fs}, testRepo, md)
	if err != nil {
		t.Fatalf("unexpected error: %s", err)
	}

	err = newTestRunner(fs, false, out).run(context.Background(), newTestCommand(testRepo, false), nil)
	if err == nil {
		t.Fatal("expected a repository behind on the structure version to fail")
	}
	if !strings.Contains(out.String(), "No layers recorded yet") {
		t.Errorf("expected the report to note there are no layers, got:\n%s", out.String())
	}
}

